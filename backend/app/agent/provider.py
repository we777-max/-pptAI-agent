from __future__ import annotations

from dataclasses import dataclass

from ..slide_ir import DeckIR, ShapeElement, TextElement


@dataclass(frozen=True)
class AgentRequest:
    prompt: str
    attachment_names: tuple[str, ...] = ()


class MockAgentProvider:
    """Deterministic provider used until a real MiniMax/OpenAI adapter is configured."""

    def generate(self, request: AgentRequest, current: DeckIR) -> DeckIR:
        title = request.prompt.strip() or "Agent 生成的演示文稿"
        if len(title) > 36:
            title = f"{title[:36]}…"
        attachment_note = ""
        if request.attachment_names:
            attachment_note = f"已参考附件：{', '.join(request.attachment_names[:3])}"
        body = attachment_note or "Agent 已根据你的需求生成内容，现在可以继续编辑、拖动和调整。"
        generated: list[TextElement | ShapeElement] = [
            TextElement(
                id="agent-title",
                frame={"x": 1.05, "y": 1.05, "w": 10.6, "h": 0.82},
                text=title,
                style={"font_size": 28, "bold": True, "color": "#111827", "font_family": "Aptos Display"},
                z_index=3,
            ),
            TextElement(
                id="agent-body",
                frame={"x": 1.08, "y": 2.15, "w": 9.3, "h": 0.8},
                text=body,
                style={"font_size": 15, "color": "#64748B"},
                z_index=3,
            ),
            ShapeElement(
                id="agent-accent",
                shape="roundRect",
                frame={"x": 1.08, "y": 3.35, "w": 4.35, "h": 1.75},
                fill={"color": "#DBEAFE"},
                stroke={"color": "#93C5FD", "width": 1},
                z_index=1,
            ),
        ]
        slide = current.slides[0].model_copy(update={"elements": generated, "notes": f"Generated by mock provider: {request.prompt}"})
        return current.model_copy(update={"title": title, "version": current.version + 1, "slides": [slide]})


def get_agent_provider() -> MockAgentProvider:
    return MockAgentProvider()
